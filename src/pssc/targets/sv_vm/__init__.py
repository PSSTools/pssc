"""``op-model-sv-vm`` target: op-model-sv's API, run by a `pssvm_pkg` engine
(design §10.2(b)).

The package keeps op-model-sv's API sections text for text -- the constants,
the register model, the API types, the import API, each `<type>_exp_if` and
the context API -- so a testbench written against op-model-sv compiles
against it unchanged. In place of the component classes, the package
functions and the factory it holds the facade (`facade.py`): a
`<type>_exp_vm` per sub-component type, the platform `<root>_vm_plat` and
`<root>_root_vm::create`.

`--with-gen` keeps op-model-sv's whole package instead, the facade beside it,
and adds `<root>_root_sel::create`, which `+pss_impl=vm|native|gen` steers: one
testbench, compiled once, runs either implementation (plan T3.4).
"""
from __future__ import annotations

import argparse
from typing import List

from ..progseq_tgt import ProgSeqTarget
from ..sections import Section


def _backend_class():
    from ..sv.backend import CLASS_SECTION, SvOpModelBackend
    from . import facade

    class SvVmBackend(SvOpModelBackend):
        """op-model-sv's API sections, then the facade over the engine."""

        #: op-model-sv's sections the facade keeps: the API, not its code.
        KEEP = ("constants", "reg_model", "api_types", "import_api",
                "context_api")

        #: `--with-gen`: all of op-model-sv's package, and `<root>_root_sel`.
        with_gen = False

        def package_sections(self, model) -> List[Section]:
            from ..sv.lower_progseq import exp_if_name
            api_ifs = {CLASS_SECTION + exp_if_name(a.comp)
                       for a in self._sub_apis(model)}
            kept = [s for s in super().package_sections(model)
                    if self.with_gen or s.name in self.KEEP
                    or s.name in api_ifs]
            sel = ([Section("root_sel",
                            lambda m: [facade.emit_root_sel(m), ""])]
                   if self.with_gen else [])
            return (kept
                    + [Section(CLASS_SECTION + facade.vm_impl_name(a.comp),
                               lambda m, a=a: [facade.emit_vm_impl(m, a), ""])
                       for a in self._sub_apis(model)]
                    + [Section("vm_platform",
                               lambda m: [facade.emit_vm_platform(m), ""]),
                       Section("root_vm",
                               lambda m: [facade.emit_root_vm(m), ""])]
                    + sel)

        def include_name(self, model, section: str) -> str:
            if section == "vm_platform":
                return facade.plat_name(model.root) + ".svh"
            if section == "root_vm":
                return facade.root_vm_name(model.root) + ".svh"
            if section == "root_sel":
                return facade.root_sel_name(model.root) + ".svh"
            return super().include_name(model, section)

        def emit_banner(self, model) -> List[str]:
            return ["// Generated by pssc (op-model-sv-vm) -- do not edit.",
                    f"// Root component: {model.tree.name}",
                    ""]

        def emit_package_open(self, model) -> List[str]:
            return [f"package {self.package_name(model)};",
                    "  import pssc_reg_pkg::*;",
                    "  import pssvm_pkg::*;",
                    ""]

        def emit_forward_decls(self, model) -> List[str]:
            # No component classes: the tree is the engine's.
            return super().emit_forward_decls(model) if self.with_gen else []

    return SvVmBackend


class SvVmTarget(ProgSeqTarget):
    name = "op-model-sv-vm"
    description = ("SystemVerilog operation-model API (as op-model-sv's) run "
                   "by a pssvm engine from a compiled image")

    @classmethod
    def backend_class(cls):
        return cls.backend_cls or _backend_class()

    def add_args(self, parser: argparse.ArgumentParser) -> None:
        super().add_args(parser)
        parser.add_argument(
            "--with-gen", dest="sv_vm_with_gen", action="store_true",
            help="op-model-sv-vm: also hold op-model-sv's generated "
                 "implementation, and <root>_root_sel::create, which "
                 "+pss_impl=vm|native|gen (default gen) steers at run time")

    def backend_for(self, opts: argparse.Namespace):
        backend = super().backend_for(opts)
        backend.with_gen = bool(getattr(opts, "sv_vm_with_gen", False))
        return backend
