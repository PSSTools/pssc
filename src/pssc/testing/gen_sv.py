"""Tests run as generated SystemVerilog: the op-model-sv package of a
fixture, every atomic test exported, run under Verilator offline.

The SV run needs no live fake. The fake's reads are deterministic and a
differential run ends at the first divergent access, so the testbench's
platform (``plat_c``, which implements the root's import API) serves each
read, and each import's output, from values given before the run (the
pyvm reference run's, in order), and logs every access and import call.
The parent compares the logged accesses with the reference's and replays
the log into a fake for the checks.

``build`` generates the package (``gen_py.generate`` with op-model-sv),
writes the testbench (the platform is generated from the import API) and
builds one Verilator binary per root component, every exported test in it
and chosen by ``+test=``. ``run`` runs one test; ``Log`` is what it made.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

from . import gen_py
from .gen_py import GenError, generate

#: the generator the tests are run through
TARGET = "op-model-sv"
#: the testbench's log lines start with this; the rest is the model's
PREFIX = "PSSGEN"
#: accesses and import calls a run may make before it is stopped
STEP_BUDGET = 100000
#: seconds a Verilator build, and a run, may take
BUILD_TIMEOUT = 600
RUN_TIMEOUT = 120


def verilator() -> Optional[str]:
    return shutil.which("verilator")


@dataclass
class Arg:
    """One argument of an import task."""

    name: str
    output: bool
    #: ``s`` string, ``n`` signed, ``u`` unsigned
    kind: str


@dataclass
class Built:
    """One Verilator binary for a root component's exported tests."""

    #: the simulation binary
    sim: str
    #: exported test -> its task on the root
    methods: Dict[str, str] = field(default_factory=dict)
    #: test -> why it was not exported
    refused: Dict[str, str] = field(default_factory=dict)
    #: test -> why the generator failed on it (a generator bug: an ERROR)
    broken: Dict[str, str] = field(default_factory=dict)
    #: the check table of the rewrite (``check_rewrite.CheckTable``)
    checks: Dict[int, Any] = field(default_factory=dict)
    setup: List[str] = field(default_factory=list)
    teardown: List[str] = field(default_factory=list)
    #: import task -> its arguments (the root's import API)
    imports: Dict[str, List[Arg]] = field(default_factory=dict)
    #: the same tests as generated Python (``gen_py.Built``): its run
    #: gives the import outputs the SV run is served (``Cache``)
    py: Any = None


_TASK = re.compile(r"^\s*pure virtual task (\w+)\((.*)\);\s*$")
_IMP_IF = re.compile(r"^\s*interface class (\w+) extends pss_mem_if;")
_ROOT = re.compile(r"^\s*class (\w+)_root #\(type Timp = (\w+)\)")
_PKG = re.compile(r"^\s*package (\w+);")


def _args(text: str) -> List[Arg]:
    out = []
    for a in (x.strip() for x in text.split(",") if x.strip()):
        words = a.split()
        out.append(Arg(name=words[-1], output=words[0] == "output",
                       kind="s" if "string" in words else
                       "n" if "signed" in words or "int" in words
                       else "u"))
    return out


def import_api(path: str) -> Dict[str, List[Arg]]:
    """The import tasks of a generated ``<root>_imp_if.svh`` (the bus
    tasks of ``pss_mem_if`` excepted)."""
    out: Dict[str, List[Arg]] = {}
    with open(path) as f:
        for line in f:
            m = _TASK.match(line)
            if m:
                out[m.group(1)] = _args(m.group(2))
    return out


def _task(name: str, args: List[Arg], proto: str) -> str:
    """``plat_c``'s implementation of import ``name``: log the call and
    each input, serve each output from the ``name`` queue."""
    body = ['      count();',
            '      $display("%s call %s");' % (PREFIX, name)]
    for a in args:
        if a.output:
            body.append('      %s = serve("%s");' % (a.name, name))
            body.append('      $display("%s ret %%0h", %s);'
                        % (PREFIX, a.name))
        elif a.kind == "s":
            body.append('      $display("%s arg s %%s", %s);'
                        % (PREFIX, a.name))
        else:
            body.append('      $display("%s arg %s %%0h", 64\'(%s));'
                        % (PREFIX, a.kind, a.name))
    return "    task %s(%s);\n%s\n    endtask" % (name, proto, "\n".join(body))


_TB = r"""// Generated by pssc test --engine gen-sv -- do not edit.
module top;
  import pssc_reg_pkg::*;
  import @PKG@::*;

  class plat_c implements @IMP_IF@;
    bit [63:0] served[string][$];
    int n;

    function void load(string path);
      int fd = $fopen(path, "r");
      string key;
      bit [63:0] v;
      if (fd == 0) $fatal(1, "cannot open %s", path);
      while ($fscanf(fd, "%s %h", key, v) == 2) served[key].push_back(v);
      $fclose(fd);
    endfunction

    function bit [63:0] serve(string key);
      if (!served.exists(key) || served[key].size() == 0) return 0;
      return served[key].pop_front();
    endfunction

    function void count();
      n++;
      if (n > @BUDGET@) begin
        $display("@PREFIX@ budget");
        $finish;
      end
    endfunction

    task rd(int w, addr_handle_t a, output bit [63:0] v);
      bit last = !served.exists("r") || served["r"].size() == 0;
      count();
      v = serve("r");
      if (w != 64) v &= (64'h1 << w) - 1;
      $display("@PREFIX@ r %0d %0h %0h", w, a, v);
      // a read the reference run did not make: the runs have diverged,
      // and a poll fed stale data would not end
      if (last) begin
        $display("@PREFIX@ exhausted");
        $finish;
      end
    endtask
    task wr(int w, addr_handle_t a, bit [63:0] d);
      count();
      $display("@PREFIX@ w %0d %0h %0h", w, a, d);
    endtask
    virtual task write8 (addr_handle_t addr, bit [7:0]  data); wr(8, addr, data); endtask
    virtual task write16(addr_handle_t addr, bit [15:0] data); wr(16, addr, data); endtask
    virtual task write32(addr_handle_t addr, bit [31:0] data); wr(32, addr, data); endtask
    virtual task write64(addr_handle_t addr, bit [63:0] data); wr(64, addr, data); endtask
    virtual task read8 (addr_handle_t addr, output bit [7:0]  data); bit [63:0] v; rd(8, addr, v); data = v[7:0]; endtask
    virtual task read16(addr_handle_t addr, output bit [15:0] data); bit [63:0] v; rd(16, addr, v); data = v[15:0]; endtask
    virtual task read32(addr_handle_t addr, output bit [31:0] data); bit [63:0] v; rd(32, addr, v); data = v[31:0]; endtask
    virtual task read64(addr_handle_t addr, output bit [63:0] data); rd(64, addr, data); endtask
@TASKS@
  endclass

  initial begin
    plat_c plat = new();
    @EXP_IF@ dut;
    string test, path;
    if ($value$plusargs("served=%s", path)) plat.load(path);
    if (!$value$plusargs("test=%s", test)) $fatal(1, "no +test=");
    dut = @ROOT@ #(plat_c)::create(plat);
@SETUP@
    case (test)
@CASES@
      default: $fatal(1, "no exported test %s", test);
    endcase
@TEARDOWN@
    $display("@PREFIX@ end");
    $finish;
  end
endmodule
"""


def _testbench(pkg: str, imp_if: str, root: str, exp_if: str,
               imports: Dict[str, List[Arg]], protos: Dict[str, str],
               methods: Sequence[str], setup: Sequence[str],
               teardown: Sequence[str]) -> str:
    tasks = "\n".join(_task(n, a, protos[n]) for n, a in imports.items())
    cases = "\n".join('      "%s": dut.%s();' % (m, m) for m in methods)
    return (_TB.replace("@PKG@", pkg).replace("@IMP_IF@", imp_if)
            .replace("@ROOT@", root).replace("@EXP_IF@", exp_if)
            .replace("@TASKS@", tasks).replace("@CASES@", cases)
            .replace("@SETUP@", "\n".join("    dut.%s();" % s for s in setup))
            .replace("@TEARDOWN@",
                     "\n".join("    dut.%s();" % s for s in teardown))
            .replace("@BUDGET@", str(STEP_BUDGET))
            .replace("@PREFIX@", PREFIX))


def _find(outputs: Sequence[str], suffix: str) -> str:
    got = [p for p in outputs if p.endswith(suffix)]
    if len(got) != 1:
        raise GenError("%s generated %d files ending %s, not 1"
                       % (TARGET, len(got), suffix))
    return got[0]


def _first(path: str, pattern) -> Tuple[str, ...]:
    with open(path) as f:
        for line in f:
            m = pattern.match(line)
            if m:
                return m.groups()
    raise GenError("%s: no line like %s" % (path, pattern.pattern))


def build(paths: Sequence[str], comp: str, tests: Sequence[str],
          out_dir: str) -> Built:
    """Generate ``comp``'s package from ``paths`` (``pssc test``'s source
    list) with each of ``tests`` that can be exported, and build it and a
    testbench with Verilator in ``out_dir``. Raises ``GenError`` when the
    build fails (the compiler's messages in it)."""
    vl = verilator()
    if vl is None:
        raise GenError("--engine gen-sv needs verilator on PATH")
    out_dir = os.path.abspath(out_dir)
    src = os.path.join(out_dir, "src")
    g = generate(paths, comp, tests, src, TARGET)
    outs = [p if os.path.isabs(p) else os.path.join(src, p)
            for p in g.outputs]
    pkg_sv = [p for p in outs if p.endswith("_pkg.sv")
              and os.path.basename(p) != "pssc_reg_pkg.sv"]
    if len(pkg_sv) != 1:
        raise GenError("%s generated %d packages, not 1"
                       % (TARGET, len(pkg_sv)))
    imp_svh = _find(outs, "_imp_if.svh")
    root_svh = _find(outs, "_root.svh")
    (pkg,) = _first(pkg_sv[0], _PKG)
    (imp_if,) = _first(imp_svh, _IMP_IF)
    root, _ = _first(root_svh, _ROOT)
    exp_if = root + "_exp_if"
    protos = {}
    with open(imp_svh) as f:
        for line in f:
            m = _TASK.match(line)
            if m:
                protos[m.group(1)] = m.group(2)
    imports = import_api(imp_svh)
    with open(root_svh) as f:
        root_text = f.read()
    methods: Dict[str, str] = {}
    broken = dict(g.broken)
    for t in g.ok:
        leaf = t.rpartition("::")[2]
        if re.search(r"virtual task %s\(\);" % re.escape(leaf), root_text):
            methods[t] = leaf
        else:
            broken[t] = "%s made no task %s on %s_root" % (TARGET, leaf, root)
    tb = os.path.join(out_dir, "tb.sv")
    with open(tb, "w") as f:
        f.write(_testbench(pkg, imp_if, root + "_root", exp_if, imports,
                           protos, sorted(set(methods.values())), g.setup,
                           g.teardown))
    obj = os.path.join(out_dir, "obj")
    cmd = [vl, "--binary", "-j", "0", "-Wno-fatal", "--top-module", "top",
           "-I" + src, "-Mdir", obj, "-o", "sim",
           os.path.join(src, "pssc_reg_pkg.sv"), pkg_sv[0], tb]
    p = subprocess.run(cmd, cwd=out_dir, capture_output=True, text=True,
                       timeout=BUILD_TIMEOUT)
    with open(os.path.join(out_dir, "build.log"), "w") as f:
        f.write(p.stdout + p.stderr)
    if p.returncode != 0:
        errs = [ln for ln in (p.stdout + p.stderr).splitlines()
                if "%Error" in ln][:5]
        raise GenError("verilator failed on the generated SV (%s):\n%s"
                       % (os.path.join(out_dir, "build.log"),
                          "\n".join(errs)))
    return Built(sim=os.path.join(obj, "sim"), methods=methods,
                 refused=g.refused, broken=broken, checks=g.checks,
                 setup=g.setup, teardown=g.teardown, imports=imports)


@dataclass
class Log:
    """What one SV run did."""

    #: each access and import call, in order: ``{"kind": "access", "rw",
    #: "width", "addr", "data"}`` or ``{"kind": "import", "name", "args",
    #: "ret"}`` (``ret``: the outputs served, a list)
    steps: List[Dict[str, Any]] = field(default_factory=list)
    #: the model's own output (messages), and Verilator's
    out: List[str] = field(default_factory=list)
    #: the run reached the end of the test (not a ``$fatal``, the budget,
    #: or a crash)
    finished: bool = False
    #: why it did not, when it did not
    error: Optional[str] = None

    def bus(self) -> List[Dict[str, Any]]:
        """The accesses, as a fake's ``bus`` (op, width, addr, data)."""
        return [{"op": "read" if s["rw"] == "r" else "write",
                 "width": s["width"], "addr": s["addr"], "data": s["data"]}
                for s in self.steps if s["kind"] == "access"]


def _signed(v: int) -> int:
    return v - (1 << 64) if v >> 63 else v


def parse(lines: Sequence[str],
          imports: Mapping[str, List[Arg]]) -> Log:
    """The ``Log`` of a run's standard output."""
    log = Log()
    call: Optional[Dict[str, Any]] = None
    for ln in lines:
        if not ln.startswith(PREFIX + " "):
            log.out.append(ln)
            continue
        w = ln[len(PREFIX) + 1:].split(" ", 2)
        tag = w[0]
        if tag in ("r", "w"):
            log.steps.append({"kind": "access", "rw": tag,
                              "width": int(w[1]), "addr": int(w[2].split()[0], 16),
                              "data": int(w[2].split()[1], 16)})
        elif tag == "call":
            call = {"kind": "import", "name": w[1], "args": [], "ret": []}
            log.steps.append(call)
        elif tag == "arg" and call is not None:
            text = ln[len(PREFIX) + 1:].split(" ", 2)[2] if len(w) > 2 else ""
            call["args"].append(text if w[1] == "s" else
                                _signed(int(text, 16)) if w[1] == "n"
                                else int(text, 16))
        elif tag == "ret" and call is not None:
            call["ret"].append(int(w[1], 16))
        elif tag == "end":
            log.finished = True
        elif tag == "exhausted":
            log.error = ("a read past the reference run's reads; the run "
                         "was stopped there")
        elif tag == "budget":
            log.error = ("more than %d bus accesses and imports; a poll "
                         "that never completes?" % STEP_BUDGET)
    if not log.finished and log.error is None:
        log.error = "the simulation stopped before the test ended: %s" % (
            "; ".join(log.out[-3:]) or "no output")
    return log


def run(built: Built, test: str, reads: Sequence[int] = (),
        returns: Optional[Mapping[str, Sequence[int]]] = None,
        work_dir: Optional[str] = None) -> Log:
    """Run exported ``test`` (``<comp>::<action>``): set-up, the test,
    tear-down. Each read returns the next of ``reads`` and each import's
    output the next of ``returns[name]`` (0 past the end)."""
    work_dir = work_dir or os.path.dirname(os.path.dirname(built.sim))
    path = os.path.join(work_dir, "served.txt")
    with open(path, "w") as f:
        for v in reads:
            f.write("r %x\n" % (v & (1 << 64) - 1))
        for name, vs in (returns or {}).items():
            for v in vs:
                f.write("%s %x\n" % (name, v & (1 << 64) - 1))
    p = subprocess.run([built.sim, "+test=" + built.methods[test],
                        "+served=" + path], cwd=work_dir,
                       capture_output=True, text=True, timeout=RUN_TIMEOUT)
    return parse((p.stdout + p.stderr).splitlines(), built.imports)


def check(built: Built, test: str, session, ref_bus: Sequence[Dict[str, Any]],
          bases: Optional[Dict[str, int]], py_session) -> Tuple[Log, Optional[str], int, int]:
    """One differential run of exported ``test``: the generated Python on
    ``py_session`` (a fresh session) gives the import outputs, the SV run
    is served those and the reference's reads (``ref_bus``), and its log is
    replayed into ``session`` (a fresh session: writes and reads to its
    fake, each import call to the doubles, as ``gen_py.Adapter`` does) for
    the checks. ``(log, divergence or None, checks passed, checks failed)``;
    the counts are of the replay, which is skipped (0, 0) when the run
    diverged or did not finish."""
    api = gen_py.Adapter(py_session, ref_bus)
    gen_py.run(built.py, test, py_session, bases=bases, hints=ref_bus,
               api=api)
    reads = [e["data"] for e in ref_bus if e["op"] == "read"]
    work = tempfile.mkdtemp(prefix="run-",
                            dir=os.path.dirname(os.path.dirname(built.sim)))
    try:
        log = run(built, test, reads=reads, returns=api.returns,
                  work_dir=work)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    diverged = gen_py.diverges(list(ref_bus), log.bus())
    if diverged or not log.finished:
        return log, diverged, 0, 0
    passed, failed = replay(built, log, session, bases, ref_bus)
    return log, None, passed, failed


def replay(built: Built, log: Log, session, bases: Optional[Dict[str, int]],
           hints: Sequence[Dict[str, Any]] = ()) -> Tuple[int, int]:
    """Apply ``log``'s steps, in order, to ``session`` (a fresh session):
    the checks of the SV run. ``(checks passed, checks failed)``; a
    ``require`` or ``fail`` that fails ends it."""
    st = session.run_state
    st.checks = built.checks
    for comp, base in (bases or {}).items():
        session.platform._place(comp, base)
    api = gen_py.Adapter(session, hints)
    try:
        for s in log.steps:
            if s["kind"] == "access":
                if s["rw"] == "r":
                    getattr(api, "read%d" % s["width"])(s["addr"])
                else:
                    getattr(api, "write%d" % s["width"])(s["addr"], s["data"])
            else:
                getattr(api, s["name"])(*s["args"])
    except gen_py._imports.RequireFailed as e:
        session.stopped = str(e)
    else:
        session.stopped = None
    return st.ledger.n_pass, st.ledger.n_fail


class Cache(gen_py.Cache):
    """The Verilator binaries of one ``pssc test --engine gen-sv`` run, one
    per root component (with its generated Python: ``Built.py``), each
    built on first use in ``out_dir/<root>``."""

    ENGINE = "gen-sv"

    def _build(self, comp: str, tests: List[str], out_dir: str) -> Built:
        sv = build(self._paths, comp, tests, os.path.join(out_dir, "sv"))
        sv.py = gen_py.build(self._paths, comp, tests,
                             os.path.join(out_dir, "py"))
        for t, why in list(sv.py.broken.items()) + list(sv.py.refused.items()):
            if t in sv.methods:
                sv.broken.setdefault(t, "gen-py, which gives the SV run its "
                                     "import outputs: %s" % why)
        return sv
