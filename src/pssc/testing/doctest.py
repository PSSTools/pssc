"""Examples in doc comments, run as tests (P5.10).

A function's doc comment may hold fenced ```` ```pss-example ```` blocks. Each
block is the body of one test: it runs in a fixture holding the documented
component as ``dut``, and does its own binding, as a hand-written test would::

    /**
     * Start a transfer.
     * ```pss-example
     * dut.initialize(base("dut"));
     * dut.start(4);
     * ```
     */
    target function void start(bit[32] n) { ... }

:func:`examples` finds the blocks in a translated model; :func:`synth` writes
the PSS that wraps them, which ``pssc test`` translates with the model.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass
from types import SimpleNamespace
from typing import List, Optional, Tuple

#: a fenced block whose info string is ``pss-example``; the body is group 1
_FENCE = re.compile(r"^[ \t]*```pss-example[ \t]*\n(.*?)^[ \t]*```[ \t]*$",
                    re.M | re.S)

#: where the wrappers are written, under the run's ``.pssunit`` directory
FILE = "doctest.pss"

#: the comment above each wrapper: where its first body line is in the source
_HEAD = re.compile(r"^// pss-example .* @ (.+):(\d+)$")
_BODY = "    function void t_example() {"
_INDENT = " " * 8


@dataclass(frozen=True)
class Example:
    """One ``pss-example`` block of a function's doc comment."""
    comp: str                   # qualified name of the documented component
    function: str
    index: int                  # 1-based, among the function's examples
    body: str
    file: Optional[str] = None  # where the function is declared
    line: Optional[int] = None
    body_line: Optional[int] = None  # the block's first line in ``file``

    @property
    def fixture(self) -> str:
        """The wrapper component's name: ``doc_<comp>_<function>_<n>``."""
        comp = self.comp.replace("::", "_")
        return f"doc_{comp}_{self.function}_{self.index}"


def blocks(doc: Optional[str]) -> List[str]:
    """The bodies of the ``pss-example`` blocks in ``doc``, in order.

    ``ast_doc`` has already taken off the comment markers (``/**``, `` * ``,
    ``///``), so a block is plain text here.
    """
    if not doc:
        return []
    return [m.group(1).rstrip() for m in _FENCE.finditer(doc)]


def examples(ctx) -> List[Example]:
    """Every ``pss-example`` block on a component function in ``ctx``.

    The type map holds a package-scope component under its qualified name and
    its short name; one declaration (file and line) is reported once, under
    the longest name.
    """
    found = {}
    for cname, cdt in ctx.type_map.items():
        if type(cdt).__name__ != "DataTypeComponent":
            continue
        for fn in getattr(cdt, "functions", None) or []:
            bodies = blocks(getattr(fn, "doc", None))
            if not bodies:
                continue
            loc = getattr(fn, "loc", None)
            key = (getattr(loc, "file", None), getattr(loc, "line", None),
                   fn.name)
            prev = found.get(key)
            if prev is not None and len(prev[0]) >= len(cname):
                continue
            found[key] = (cname, fn.name, bodies, key[0], key[1])
    out: List[Example] = []
    for cname, fname, bodies, file, line in found.values():
        starts = _fences(file, line)
        if len(starts) != len(bodies):
            starts = [None] * len(bodies)
        out.extend(Example(cname, fname, i, body, file, line,
                           None if s is None else s + 1)
                   for i, (body, s) in enumerate(zip(bodies, starts), 1))
    return out


def _read(file: Optional[str]) -> List[str]:
    try:
        with open(file) as f:
            return f.read().splitlines()
    except (OSError, TypeError, UnicodeDecodeError):
        return []


def _fences(file: Optional[str], line: Optional[int]) -> List[int]:
    """The lines (1-based) of the ```` ```pss-example ```` fences in the doc
    comment just above the declaration at ``file:line``, in order."""
    lines = _read(file)
    if not line or line > len(lines) + 1:
        return []
    out = []
    ln = line - 2                       # 0-based, the line above the decl
    while ln >= 0:
        text = lines[ln].strip()
        if not text.startswith(("*", "/**", "///")) and not text.endswith("*/"):
            break
        if "```pss-example" in text:
            out.append(ln + 1)
        if text.startswith("/**"):
            break
        ln -= 1
    return out[::-1]


def synth(exs: List[Example]) -> str:
    """The PSS for ``exs``: one ``pssunit_pkg::fixture_c`` per example."""
    parts = ["// Generated by pssc test from doc-comment examples; do not edit.\n",
             "import pssunit_pkg::*;\n"]
    for ex in exs:
        body = "\n".join(_INDENT + ln if ln.strip() else ""
                         for ln in ex.body.splitlines())
        head = f"// pss-example {ex.comp}::{ex.function} {ex.index}"
        if ex.file:
            head += f" @ {ex.file}:{ex.body_line or ex.line}"
        parts.append(
            f"\n{head}\n"
            f"component {ex.fixture} : pssunit_pkg::fixture_c {{\n"
            f"    {ex.comp} dut;\n"
            f"    @pssunit_pkg::test\n"
            f"{_BODY}\n"
            f"{body}\n"
            f"    }}\n"
            f"}}\n")
    return "".join(parts)


def _is_wrapper(file: Optional[str]) -> bool:
    return bool(file) and os.path.basename(file) == FILE \
        and os.path.basename(os.path.dirname(file)) == ".pssunit"


def _wrapper(lines: List[str], line: int):
    """For 1-based ``line`` of a wrapper file: (source file, source line of
    the first body line, wrapper line of the first body line), or None."""
    ln = min(line, len(lines)) - 1
    while ln >= 0:
        m = _HEAD.match(lines[ln])
        if m:
            for b in range(ln + 1, len(lines)):
                if lines[b] == _BODY:
                    return m.group(1), int(m.group(2)), b + 2
            return None
        ln -= 1
    return None


def source(file: Optional[str], line: int,
           col: int = 0) -> Optional[Tuple[str, int, int]]:
    """Where ``file:line:col`` of the generated wrappers is in the doc comment
    it came from; None when ``file`` is not the wrappers' file or the place
    is outside an example's body."""
    if not _is_wrapper(file):
        return None
    lines = _read(file)
    w = _wrapper(lines, line)
    if w is None or line < w[2]:
        return None
    src, first, gen_first = w
    src_line = first + line - gen_first
    text = lines[line - 1].lstrip() if line <= len(lines) else ""
    src_lines = _read(src)
    if text and 0 < src_line <= len(src_lines):
        i = src_lines[src_line - 1].find(text)
        if i >= 0 and col:
            col = i + 1 + max(col - 1 - (len(lines[line - 1]) - len(text)), 0)
    return src, src_line, col


def item_loc(loc):
    """``(loc, end_line)`` for a test declared at ``loc``: for a wrapper's
    test, the example's fences in the doc comment (so a ``FILE:LINE`` spec on
    the example selects it); otherwise None."""
    file = getattr(loc, "file", None)
    if not _is_wrapper(file):
        return None
    lines = _read(file)
    w = _wrapper(lines, loc.line + 1)
    if w is None:
        return None
    src, first, gen_first = w
    n = 0
    while gen_first - 1 + n < len(lines) and lines[gen_first - 1 + n] != "    }":
        n += 1
    return SimpleNamespace(file=src, line=first - 1, pos=1), first + n
