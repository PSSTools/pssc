"""T1.9a/b: the Python host API (``pssc.testing.vm``): a platform, and
the doubles ``@pv.implements``, ``@pv.mock``, ``@pv.spy`` with ``ctx``.

A ``pv.Platform`` has op-model-py's ``<Root>ImportApi`` shape, so
``pssc_rt.check_import_api`` passes against the Protocol generated from the
same model, and a run's memory accesses, user imports and messages reach it.
"""
from __future__ import annotations

import importlib
import sys

import pytest

pytest.importorskip("pssparser")
pytest.importorskip("zuspec.be.bc")

from pssc.testing import compile_op_model
import pssc.testing.vm as pv

#: The product model: what op-model-py generates from, without pssunit_pkg
#: (whose own imports a pssunit run provides, not the product's platform).
MODEL = """\
import addr_reg_pkg::*;

import function bit[32] plat_id();
import function void plat_delay_us(bit[32] us);

component board_c {
    function bit[32] probe() {
        plat_delay_us(3);
        write32(make_handle_from_handle(0, 0x100), 7);
        return read32(make_handle_from_handle(0, 0x100)) + plat_id();
    }
    function bit[32] scale(bit[32] x) {
        return x * 2;
    }
}
"""

SUITE = """\
import pssunit_pkg::*;

component board_f : fixture_c {
    rt_c rt;
    board_c board;
    @pssunit_pkg::test
    function void t_probe() {
        rt.check_eq_int(board.probe(), 7 + 0x5A, "probe");
    }
    @pssunit_pkg::test
    function void t_scale() {
        rt.check_eq_int(board.scale(4), 8, "scale");
    }
}
"""


class Board(pv.Platform):
    def __init__(self):
        super().__init__()
        self.delays = []

    def plat_id(self):
        return 0x5A

    def plat_delay_us(self, us):
        self.delays.append(us)


@pytest.fixture(scope="module")
def files(tmp_path_factory):
    d = tmp_path_factory.mktemp("pv")
    (d / "model.pss").write_text(MODEL)
    (d / "suite.pss").write_text(SUITE)
    return [d / "model.pss", d / "suite.pss"]


@pytest.fixture(scope="module")
def import_api(files):
    """``BoardImportApi`` and ``pssc_rt``, generated by op-model-py."""
    with compile_op_model("op-model-py", sources=[str(files[0])],
                          root="board_c") as outcome:
        sys.path.insert(0, str(outcome.out_dir))
        try:
            mods = [f.stem for f in outcome.out_dir.glob("*.py")
                    if f.stem != "pssc_rt"]
            for name in mods + ["pssc_rt"]:
                sys.modules.pop(name, None)
            rt = importlib.import_module("pssc_rt")
            mod = importlib.import_module(mods[0])
        finally:
            sys.path.remove(str(outcome.out_dir))
        yield mod.BoardImportApi, rt


def test_a_platform_passes_check_import_api(import_api):
    proto, rt = import_api
    assert rt.check_import_api(Board(), proto) == []
    # the base class alone lacks the user imports, by name
    missing = rt.check_import_api(pv.Platform(), proto)
    assert any(m.startswith("plat_id") for m in missing)


def test_a_run_reaches_the_platform(files):
    board = Board()
    s = pv.load(files, root="board_f", platform=board)
    assert s.run_test("board_f::t_probe", seed=1) == (1, 0, 0)
    assert board.delays == [3]
    assert ("write", 32, 0x100, 7) in board.log
    assert ("read", 32, 0x100, 7) in board.log


def test_a_missing_import_is_named(files):
    from zuspec.be.bc.interp import VMError

    s = pv.load(files, root="board_f", platform=pv.Platform())
    with pytest.raises(VMError, match="plat_delay_us") as ei:
        s.run_test("board_f::t_probe", seed=1)
    # located at the call, never a silent 0
    line = MODEL[:MODEL.index("plat_delay_us(3)")].count("\n") + 1
    assert ei.value.location.startswith(f"{files[0]}:{line}:")


#: a module-level double: ``Session.use(<this module>)`` takes it
MOCKED = []


@pv.mock("board_c::scale")
def _scale(ctx, self_, x):
    MOCKED.append(x)
    ctx.raise_irq(3)
    return 8


def test_implements_comes_before_the_platform(files):
    from zuspec.be.bc.trace import MemorySink
    from zuspec.be.bc.trace import events as ev

    r = pv.Registry()

    @r.implements("plat_delay_us")
    def delay(ctx, us):
        ctx.time.advance_us(us)

    board, sink = Board(), MemorySink()
    s = pv.load(files, root="board_f", platform=board, use=[r], events=sink,
                watch=ev.EV_IMPORT)
    assert s.run_test("board_f::t_probe", seed=1) == (1, 0, 0)
    assert board.delays == []                      # the platform's is not called
    assert s.ctx.time.now == 3 * s.ticks_per_us
    mocked = {e.detail["name"].rpartition("::")[2]: e.detail["mocked"]
              for e in sink.events if e.kind == "import"}
    assert mocked == {"plat_delay_us": True, "plat_id": False}


@pytest.mark.parametrize("engine", ["py", "c"])
def test_a_mock_replaces_a_function_every_test(files, engine):
    class IrqBoard(Board):
        def __init__(self):
            super().__init__()
            self.irqs = []

        def raise_irq(self, n):
            self.irqs.append(n)

    MOCKED.clear()
    board = IrqBoard()
    s = pv.load(files, root="board_f", platform=board, engine=engine)
    s.use(sys.modules[__name__])
    assert s.run_test("board_f::t_scale", seed=1) == (1, 0, 0)
    assert s.run_test("board_f::t_scale", seed=2) == (1, 0, 0)   # re-applied
    assert MOCKED == [4, 4]
    assert s.irqs == [3, 3] and board.irqs == [3, 3]


def test_a_spy_calls_through_and_records(files):
    r, seen = pv.Registry(), []
    r.spy("board_c::scale")(seen.append)
    s = pv.load(files, root="board_f", platform=Board(), use=[r])
    assert s.run_test("board_f::t_scale", seed=1) == (1, 0, 0)
    want = [pv.Call("board_c::scale", [4], 8)]
    assert seen == want and s.calls["board_c::scale"] == want
    # a module that declares no doubles is refused
    with pytest.raises(ValueError, match="no doubles"):
        s.use(pytest)


@pytest.mark.parametrize("engine", ["py", "c"])
def test_a_spy_records_the_same_on_both_engines(files, engine):
    """P4.8c: on the C engine a spy sees the calls of the run's trace when
    it ends, with the same arguments and results as on the Python VM."""
    r, seen = pv.Registry(), []
    r.spy("board_c::scale")(seen.append)
    s = pv.load(files, root="board_f", platform=Board(), use=[r],
                engine=engine)
    assert s.run_test("board_f::t_scale", seed=1) == (1, 0, 0)
    assert seen == [pv.Call("board_c::scale", [4], 8)]
