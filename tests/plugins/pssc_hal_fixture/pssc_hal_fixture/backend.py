"""The HAL fixture's target: `op-model-c`, as a stateless API.

The model says what the API is, in three annotations (`model/dev.pss`):
`hal_fx_pkg::api_s` on the root gives the function prefix,
`hal_fx_pkg::bases_s` on its constructor the C type of a base, and
`hal_fx_pkg::extern_s` marks a type the platform declares.

The platform supplies `dev_access.h`: `DEV_READ32_INTO(base, REG, i, out)`,
a statement (so the target asks for `reg_read_form = "statement"`),
`DEV_WRITE32(base, REG, i, v)`, `DEV_FIELD_SET(REG, F, x, v)` and
`DEV_FIELD_GET(REG, F, v)`, over the `<REG>_OFF`, `<REG>_STRIDE`,
`<REG>_<F>_LSB` and `<REG>_<F>_MASK` this target writes to `<prefix>_map.h`.
"""
from __future__ import annotations

import json

from pssc import annotations
from pssc.diag import Refusal
from pssc.targets import reg_layout
from pssc.targets.c.backend import COpModelBackend
from pssc.targets.c.lower_progseq import CBodyEmitter
from pssc.targets.c.style import CStylePolicy
from pssc.targets.c_progseq_tgt import CProgSeqTarget
from pssc.targets.sections import remove

API = "hal_fx_pkg::api_s"
BASES = "hal_fx_pkg::bases_s"
EXTERN = "hal_fx_pkg::extern_s"


def reg_name(acc) -> str:
    """A register's macro name: its path from the component, `CTL_MODE`."""
    return "_".join(acc.path).upper()


class HalStyle(CStylePolicy):
    name = "hal-fixture"
    description = "a stateless API over the platform's register macros"

    def is_extern_type(self, dtype):
        return annotations.of(dtype, EXTERN) is not None

    def seam_includes(self, model, s):
        # The platform's macros, then the map they read; pssc's seam is
        # not used.
        return ['#include "dev_access.h"', f'#include "{s.prefix}_map.h"']

    def seam_headers(self, link_style):
        return ()           # ...so none is copied

    def banner(self, model, s):
        # op-model-c's states the ABI of a component object; there is none.
        return [f"/* Generated by pssc (op-model-hal-fixture) from "
                f"{model.root.name} -- do not edit. */"]


class HalEmitter(CBodyEmitter):
    """Register accesses in the platform's macros, and calls that pass
    bases instead of a handle."""

    def _where(self, ra, lw) -> str:
        """`base, REG, index`: which window, which register, which element."""
        base = dict(self.op_ctx.api.bases(self.fn)).get(ra.group_path)
        if base is None:
            raise Refusal(f"register group '{'.'.join(ra.group_path)}' is "
                          f"not one of the root's, so it has no base here")
        if len(lw.indices) > 1:
            raise Refusal(f"'{reg_name(ra.accessor)}' is reached through "
                          f"more than one array index")
        return f"{base}, {reg_name(ra.accessor)}, " \
               f"{lw.indices[0] if lw.indices else 0}"

    def reg_access(self, ra, lw):
        if ra.method in ("read", "read_val"):
            # Never printed: every read is a statement (`reg_read_into`).
            # pssc still asks for this spelling to find the read in a
            # conversion, so it must be unique to this read.
            return f"DEV_READ32({self._where(ra, lw)})"
        if ra.method == "write_val":
            return f"DEV_WRITE32({self._where(ra, lw)}, {lw.args[0]})"
        raise Refusal(f"'{ra.method}' has no spelling in this API")

    def reg_read_into(self, ra, lw, local):
        return f"DEV_READ32_INTO({self._where(ra, lw)}, {local})"

    def reg_masked_write_inline(self, ra, lw):
        return None         # read, set each field, write: pssc's shape

    partial_field_writes = False    # a part of a field: pssc merges the mask

    def reg_value_local(self, ra, lw):
        return "uint32_t", "data"

    def reg_value_field_set(self, local, fs, value, ra, lw, mask):
        return f"DEV_FIELD_SET({reg_name(ra.accessor)}, {fs.name}, " \
               f"({value}), {local})"

    def reg_value_field_get(self, value, fs, ra, lw):
        return f"DEV_FIELD_GET({reg_name(ra.accessor)}, {fs.name}, {value})"

    def model_call(self, callee, args, ctx, handle):
        name = ctx.op_api.signature(callee, ctx)[1]
        bases = [p for _, p in ctx.op_api.bases(callee)]
        return f"{name}({', '.join(bases + args)})"


class HalBackend(COpModelBackend):
    style_cls = HalStyle
    body_emitter_cls = HalEmitter

    def bases(self, fn):
        """`[(group path, parameter)]`: the windows ``fn`` takes."""
        return self.model.unpacked_signature(fn)

    def handle_param(self, fn, ctx):
        return None

    def signature(self, fn, ctx):
        ret, _, params = super().signature(fn, ctx)
        m = self.model
        prefix = (annotations.of(m.root, API) or {}).get("prefix") or ctx.prefix
        base_t = (annotations.of(m.ctor(m.root), BASES) or {}).get(
            "c_type", "uintptr_t")
        return (ret, f"{prefix}_{fn.name}",
                [(base_t, p) for _, p in self.bases(fn)] + params)

    def linkage(self, fn, ctx):
        return "extern" if any(fn is e for e in self.model.exports) \
            else "static"

    # No object: no lifecycle, no handle struct, no register-map layout.
    def emit_lifecycle_decls(self, node, ctx):
        return []

    def emit_lifecycle(self, node, ctx):
        return []

    def header_sections(self, model, s):
        return remove(remove(super().header_sections(model, s), "reg_map"),
                      "handles")

    def impl_sections(self, model, s):
        return remove(super().impl_sections(model, s), "accessors")

    def regs_text(self, model, s):
        return ""

    def emit_extra_files(self, model, s):
        guard = f"{s.prefix.upper()}_MAP_H"
        lines = [f"/* Register map for {s.prefix}. Generated. */",
                 f"#ifndef {guard}", f"#define {guard}"]
        for acc in reg_layout.collect_accessors(model.root):
            r = reg_name(acc)
            lines += [f"#define {r}_OFF 0x{acc.const_off:X}u",
                      f"#define {r}_STRIDE 0x{(acc.strides or (0,))[0]:X}u"]
            lines += [f"#define {r}_{f.name}_LSB {f.lsb}\n"
                      f"#define {r}_{f.name}_MASK 0x{f.mask:X}u"
                      for f in acc.fields]
        lines.append(f"#endif /* {guard} */")
        ctx = self.op_ctx(model.root)
        api = [{"name": self.signature(fn, ctx)[1],
                "bases": [p for _, p in self.bases(fn)],
                "exported": self.linkage(fn, ctx) == "extern"}
               for fn in model.operations(model.root)]
        return {f"{s.prefix}_map.h": "\n".join(lines) + "\n",
                f"{s.prefix}_api.json": json.dumps(api, indent=2) + "\n"}


class HalFixtureTarget(CProgSeqTarget):
    name = "op-model-hal-fixture"
    description = "a stateless C API over platform register macros " \
                  "(pssc-hal-fixture)"
    derives_from = "op-model-c"
    reg_read_form = "statement"
    backend_cls = HalBackend
